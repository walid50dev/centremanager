import assert from 'node:assert/strict';
import { createServer } from 'vite';
const storage = new Map();
globalThis.localStorage = { getItem: key => storage.get(key) ?? null, setItem: (key, value) => storage.set(key, String(value)) };
globalThis.window = { setTimeout };
const server = await createServer({ optimizeDeps:{ noDiscovery:true }, server:{ middlewareMode:true, hmr:false }, appType:'custom' });
try {
  const { devInvoke: call } = await server.ssrLoadModule('/src/services/settingsDevBackend.ts');
  const old = await call('cmd_get_active_school_year');
  assert.equal(await call('cmd_get_enrollment_fee'), 0);
  await assert.rejects(call('cmd_set_enrollment_fee', { amount:-1 }), /invalide/i);
  await call('cmd_set_enrollment_fee', { amount:20000 });
  const id = await call('cmd_create_student', { data:{ full_name:'Salma Mansouri', first_name:'Salma', last_name:'Mansouri', phone:'0661234567', guardian_name:'Rachid Mansouri', guardian_phone:'0661234567', enrollment_date:'2026-09-01', level_id:1, status:'actif', enrollment_fee_cents:20000 } });
  const groups = await call('cmd_get_groups');
  await assert.rejects(call('cmd_enroll_student_batch', { enrollments:[
    { student_id:id, group_id:groups[0].id, start_date:'2026-09-01' },
    { student_id:id, group_id:999999, start_date:'2026-09-01' },
  ] }));
  assert.equal((await call('cmd_get_student_invoices', { studentId:id })).length, 0, 'batch rollback includes the fee');
  const first = await call('cmd_enroll_student', { studentId:id, groupId:groups[0].id, startDate:'2026-09-01' });
  assert.ok(first.enrollment_fee_invoice_id); assert.equal(first.enrollment_fee_amount_cents, 20000);
  const second = await call('cmd_enroll_student', { studentId:id, groupId:groups[1].id, startDate:'2026-09-01' });
  assert.equal(second.enrollment_fee_invoice_id, null);
  let invoices = await call('cmd_get_student_invoices', { studentId:id });
  let fee = invoices.find(i => i.kind === 'enrollment_fee');
  assert.equal(invoices.filter(i => i.kind === 'enrollment_fee').length, 1);
  assert.equal(fee.amount_cents, 20000); assert.equal(fee.school_year_label, old.label); assert.equal(fee.status, 'impayé');
  const paymentId = await call('cmd_record_payment', { studentId:id, invoiceIds:[fee.id], amountCents:5000, method:'espèces' });
  fee = (await call('cmd_get_student_invoices', { studentId:id })).find(i => i.kind === 'enrollment_fee');
  assert.equal(fee.status, 'partiel'); assert.equal(fee.remaining_cents, 15000);
  const receipt = await call('cmd_get_receipt_data', { paymentId });
  assert.equal(receipt.items[0].kind, 'enrollment_fee'); assert.equal(receipt.items[0].month, old.label); assert.equal(receipt.items[0].amount, 5000);
  const paymentId2 = await call('cmd_record_payment', { studentId:id, invoiceIds:[fee.id], amountCents:15000, method:'espèces' });
  assert.ok(paymentId2); assert.equal((await call('cmd_get_student_invoices', { studentId:id })).find(i => i.kind === 'enrollment_fee').status, 'payé');
  const exported = await call('cmd_export_year_data', { yearId:old.id, section:'payments' });
  assert.equal(exported.filter(p => p.invoice_kind === 'enrollment_fee').reduce((sum, p) => sum + Number(p.amount_cents), 0), 20000);
  const now = new Date();
  const kpis = await call('cmd_get_dashboard_kpis', { month:now.getMonth()+1, year:now.getFullYear() });
  const store = JSON.parse(storage.get('centremanager.dev.settings_store_v1'));
  assert.equal(kpis.monthly_revenue_cents, store.payments.filter(p => p.school_year_id === old.id && p.created_at.startsWith(`${now.getFullYear()}-${String(now.getMonth()+1).padStart(2,'0')}`)).reduce((sum,p) => sum+p.amount_cents,0));
  const next = await call('cmd_create_school_year', { label:'2030-2031', startDate:'2030-09-01', endDate:'2031-06-30' });
  await call('cmd_switch_school_year', { yearId:next }); assert.equal(await call('cmd_get_enrollment_fee'), 0);
  await call('cmd_import_students', { studentIds:[id], targetYearId:next });
  await call('cmd_import_groups', { groupIds:[groups[0].id,groups[1].id], targetYearId:next });
  const newGroups = await call('cmd_get_groups');
  const studentRow = (await call('cmd_get_student_detail', { id })).student;
  await call('cmd_update_student', { id, data: { ...studentRow, enrollment_fee_cents: 30000 } });
  const result = await call('cmd_enroll_student', { studentId:id, groupId:newGroups[0].id, startDate:'2030-09-01' });
  assert.equal(result.enrollment_fee_amount_cents, 30000);
  invoices = await call('cmd_get_student_invoices', { studentId:id });
  assert.equal(invoices.filter(i => i.kind === 'enrollment_fee').length, 1); assert.equal(invoices.find(i => i.kind === 'enrollment_fee').school_year_label, '2030-2031');
  const zeroStudent = await call('cmd_create_student', { data:{ full_name:'Aya Mansouri', first_name:'Aya', last_name:'Mansouri', phone:'0661234567', guardian_name:'Rachid Mansouri', guardian_phone:'0661234567', enrollment_date:'2030-09-01', level_id:1, status:'actif' } });
  await call('cmd_set_enrollment_fee', { amount:0 });
  const zero = await call('cmd_enroll_student', { studentId:zeroStudent, groupId:newGroups[0].id, startDate:'2030-09-01' });
  assert.equal(zero.enrollment_fee_invoice_id, null);
  assert.equal((await call('cmd_get_student_invoices', { studentId:zeroStudent })).filter(i => i.kind === 'enrollment_fee').length, 0);
  await call('cmd_set_enrollment_fee', { amount:25000 });
  await call('cmd_delete_to_trash', { entityType:'group', entityId:newGroups[0].id });
  await call('cmd_empty_trash');
  const later = await call('cmd_enroll_student', { studentId:zeroStudent, groupId:newGroups[1].id, startDate:'2030-09-01' });
  assert.equal(later.enrollment_fee_invoice_id, null, 'zero decision survives deleting the first group and is never charged later');
  assert.equal((await call('cmd_get_student_invoices', {studentId:zeroStudent})).filter(i => i.kind === 'enrollment_fee').length, 0);
  await call('cmd_switch_school_year', { yearId:old.id }); assert.equal(await call('cmd_get_enrollment_fee'), 20000);
  await assert.rejects(call('cmd_set_enrollment_fee', { amount:123, yearId:next }), /changé/);
  await call('cmd_delete_to_trash', { entityType:'group', entityId:groups[0].id });
  await call('cmd_empty_trash');
  fee = (await call('cmd_get_student_invoices', { studentId:id })).find(i => i.kind === 'enrollment_fee');
  assert.equal(fee.status, 'payé', 'fee survives deleting its first group');
  await call('cmd_delete_school_year', { yearId:next });
  assert.equal((await call('cmd_get_student_invoices', { studentId:id })).find(i => i.kind === 'enrollment_fee').id, first.enrollment_fee_invoice_id);
  console.log('Enrollment fee: per year, uniqueness, zero, partial/full payment, receipts, dashboard and exports passed');
} finally { await server.close(); }

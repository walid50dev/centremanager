import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
import { createServer } from 'vite';
const dom = new JSDOM('<!doctype html><html><body><div id="root"></div></body></html>', { url: 'http://localhost/' });
Object.assign(globalThis, { window: dom.window, document: dom.window.document, localStorage: dom.window.localStorage, Element: dom.window.Element, HTMLElement: dom.window.HTMLElement, IS_REACT_ACT_ENVIRONMENT: true });
const React = await import('react');
const { act } = React;
const { createRoot } = await import('react-dom/client');
const { BrowserRouter } = await import('react-router-dom');
const server = await createServer({ optimizeDeps: { noDiscovery: true }, server: { middlewareMode: true }, appType: 'custom' });
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
const q = selector => { const el = document.querySelector(selector); assert.ok(el, `Missing ${selector}`); return el; };
const click = async el => act(async () => { el.click(); await wait(120); });
try {
  await server.ssrLoadModule('/src/i18n/index.ts');
  const { useAppStore } = await server.ssrLoadModule('/src/stores/appStore.ts');
  const { devInvoke } = await server.ssrLoadModule('/src/services/settingsDevBackend.ts');
  const { default: Sidebar } = await server.ssrLoadModule('/src/components/layout/Sidebar.tsx');
  const { default: ImportButton } = await server.ssrLoadModule('/src/components/year-import/ImportButton.tsx');
  const { yearExportApi, EXPORT_COLUMNS } = await server.ssrLoadModule('/src/services/yearExport.ts');
  const initial = await devInvoke('cmd_get_active_school_year');
  const originalStudents = (await devInvoke('cmd_get_students')).data;
  assert.ok(originalStudents.length);
  const newId = await devInvoke('cmd_create_school_year', { label:'2025-2026', startDate:'2025-09-01', endDate:'2026-06-30' });
  await useAppStore.getState().loadSchoolYears();
  let imported = 0;
  const root = createRoot(q('#root'));
  await act(async () => { root.render(React.createElement(BrowserRouter, { future: { v7_startTransition: true, v7_relativeSplatPath: true } }, React.createElement(Sidebar), React.createElement(ImportButton, { kind:'students', onImported: () => imported++ }))); await wait(200); });
  const select = q('[data-testid="sidebar-school-year"]');
  await act(async () => { select.value = String(newId); select.dispatchEvent(new dom.window.Event('change', { bubbles: true })); });
  assert.equal(useAppStore.getState().activeSchoolYear.id, initial.id, 'switch waits for confirmation');
  const dialog = q('[role="dialog"]');
  assert.match(dialog.textContent, /2025-2026/);
  await click([...dialog.querySelectorAll('button')].find(button => button.textContent.trim() === 'Changer'));
  await act(async () => { await wait(350); });
  await act(async () => { await wait(200); });
  assert.equal(useAppStore.getState().activeSchoolYear.id, newId);
  assert.equal((await devInvoke('cmd_get_students')).data.length, 0);
  assert.equal((await devInvoke('cmd_get_groups')).length, 0);
  assert.equal((await devInvoke('cmd_get_teachers')).length, 0);
  assert.equal((await devInvoke('cmd_get_timetable')).length, 0);
  await click(q('[data-testid="import-students"]'));
  await act(async () => { await wait(150); });
  const check = q(`[data-testid="import-item-${originalStudents[0].id}"]`);
  await click(check);
  await click(q('[data-testid="import-submit"]'));
  await act(async () => { await wait(250); });
  assert.equal(imported, 1);
  assert.deepEqual((await devInvoke('cmd_get_students')).data.map(s => s.id), [originalStudents[0].id]);
  assert.deepEqual(await devInvoke('cmd_get_student_enrollments', { studentId:originalStudents[0].id }), []);
  await click(q('[data-testid="import-students"]'));
  await act(async () => { await wait(200); });
  assert.equal(q(`[data-testid="import-item-${originalStudents[0].id}"]`).disabled, true);
  const summary = await yearExportApi.summary(newId);
  assert.equal(summary.students, 1); assert.equal(summary.groups, 0); assert.equal(summary.revenue_cents, 0);
  const sourceGroups = await devInvoke('cmd_get_importable_groups', { prevYearId: initial.id });
  assert.ok(sourceGroups.length > 0);
  const sourceDetails = await devInvoke('cmd_get_group_detail', { id: sourceGroups[0].id });
  assert.equal(await devInvoke('cmd_import_groups', { groupIds: [sourceGroups[0].id], targetYearId: newId }), 1);
  assert.equal(await devInvoke('cmd_import_groups', { groupIds: [sourceGroups[0].id], targetYearId: newId }), 0);
  const newGroups = await devInvoke('cmd_get_groups');
  assert.equal(newGroups.length, 1);
  assert.equal(newGroups[0].schedules.length, sourceDetails.group.schedules.length);
  assert.equal((await devInvoke('cmd_get_group_detail', { id: newGroups[0].id })).students.length, 0);
  for (const section of ['students','groups','teachers','payments','expenses','salaries']) {
    const exported = await yearExportApi.data(newId, section);
    assert.ok(Array.isArray(exported));
    for (const row of exported) assert.deepEqual(Object.keys(row).sort(), [...EXPORT_COLUMNS[section]].sort(), `columns: ${section}`);
  }
  const rows = await yearExportApi.data(newId, 'students');
  const xlsx = await import('xlsx');
  const wb = xlsx.utils.book_new(); xlsx.utils.book_append_sheet(wb, xlsx.utils.json_to_sheet(rows, { header: EXPORT_COLUMNS.students }), 'students');
  const bytes = xlsx.write(wb, { type:'buffer', bookType:'xlsx' });
  const loaded = xlsx.read(bytes, { type:'buffer' });
  const table = xlsx.utils.sheet_to_json(loaded.Sheets.students, { header:1 });
  assert.deepEqual(table[0], EXPORT_COLUMNS.students); assert.equal(table[1][0], String(originalStudents[0].id));
  await devInvoke('cmd_switch_school_year', { yearId: initial.id });
  assert.equal((await devInvoke('cmd_get_students')).data.length, originalStudents.length);
  await devInvoke('cmd_switch_school_year', { yearId: newId });
  assert.equal((await devInvoke('cmd_get_students')).data.length, 1);
  await act(async () => { root.unmount(); });
  console.log('Year workflow: confirmed switch, scoped mock lists, selective import, no enrollments and XLSX verified');
} finally { await server.close(); dom.window.close(); }

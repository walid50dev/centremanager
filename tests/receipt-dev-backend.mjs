// Run: node tests/receipt-dev-backend.mjs
import assert from 'node:assert/strict';
import { createServer } from 'vite';
const storage = new Map();
globalThis.localStorage = { getItem: key => storage.get(key) ?? null, setItem: (key, value) => storage.set(key, String(value)) };
globalThis.window = { setTimeout };
const server = await createServer({ optimizeDeps: { noDiscovery: true }, server: { middlewareMode: true }, appType: 'custom' });
try {
  const { devInvoke } = await server.ssrLoadModule('/src/services/settingsDevBackend.ts');
  const logo = 'data:image/png;base64,YWJj';
  await devInvoke('cmd_set_centre_info', { name: 'Centre Test', logo });
  assert.deepEqual(await devInvoke('cmd_get_centre_info'), { name: 'Centre Test', logo });
  await devInvoke('cmd_set_centre_info', { name: 'Centre Test', logo: null });
  assert.deepEqual(await devInvoke('cmd_get_centre_info'), { name: 'Centre Test', logo: null });
  await assert.rejects(devInvoke('cmd_set_centre_info', { name: '', logo: null }));
  await assert.rejects(devInvoke('cmd_set_centre_info', { name: 'x', logo: 'data:image/gif;base64,YWJj' }));
  const maximum = 'data:image/png;base64,' + Buffer.alloc(2 * 1024 * 1024).toString('base64');
  await devInvoke('cmd_set_centre_info', { name: 'Centre Test', logo: maximum });
  const tooLarge = 'data:image/png;base64,' + Buffer.alloc(2 * 1024 * 1024 + 1).toString('base64');
  await assert.rejects(devInvoke('cmd_set_centre_info', { name: 'Centre Test', logo: tooLarge }));
  await devInvoke('cmd_set_centre_info', { name: 'Centre Test', logo });
  const key = 'centremanager.dev.settings_store_v1';
  const store = JSON.parse(storage.get(key));
  const student = store.students[0];
  student.level_id = 10;
  store.enrollments = store.groups.slice(0, 3).map((group, i) => ({ id: 100+i, student_id: student.id, group_id: group.id, start_date: '2025-11-01', status: 'actif', end_date: null }));
  store.invoices = store.enrollments.map((enrollment, i) => ({ id: 100+i, enrollment_id: enrollment.id, period_month: 11, period_year: 2025, amount_cents: 30000, paid_amount_cents: 0, status: 'impayé', due_date: '2025-11-01', created_at: '2025-11-01' }));
  store.payments = []; store.receipts = []; store.nextPaymentId = 100; store.nextReceiptId = 1;
  storage.set(key, JSON.stringify(store));
  const record = (ids, amount) => devInvoke('cmd_record_payment', { studentId: student.id, invoiceIds: ids, amountCents: amount, method: 'espèces', notes: null });
  const first = await record([100], 12000);
  const single = await devInvoke('cmd_get_receipt_data', { paymentId: first });
  assert.equal(single.items.length, 1); assert.equal(single.items[0].amount, 12000); assert.equal(single.items[0].month, 'Novembre 2025');
  assert.equal(single.total, 12000); assert.equal(single.centre_name, 'Centre Test'); assert.equal(single.centre_logo, logo); assert.equal(single.student_level, 'Tronc Commun');
  const second = await record([100, 101, 102], 75000);
  const sameSecond = JSON.parse(storage.get(key));
  sameSecond.payments.forEach(payment => { payment.created_at = '2025-11-01 12:00:00'; });
  storage.set(key, JSON.stringify(sameSecond));
  assert.equal((await devInvoke('cmd_get_receipt_data', { paymentId: first })).total, 12000);
  const data = await devInvoke('cmd_get_receipt_data', { paymentId: second });
  assert.equal(data.items.length, 3); assert.deepEqual(data.items.map(i => i.amount), [18000, 30000, 27000]);
  assert.equal(data.items.reduce((sum, item) => sum + item.amount, 0), data.total);
  assert.ok(data.items.every(i => i.subject && i.group_name && i.month === 'Novembre 2025'));
  const receiptId = await devInvoke('cmd_create_receipt', { paymentId: second + 1 });
  assert.equal((await devInvoke('cmd_get_receipt_data', { receiptId })).receipt_number, data.receipt_number, 'all allocations resolve to the same receipt');
  const next = await record([102], 5000);
  const advance = await devInvoke('cmd_get_receipt_data', { paymentId: next });
  assert.deepEqual(advance.items.map(i => [i.kind, i.amount]), [['invoice', 3000], ['advance', 2000]]);
  assert.equal(advance.total, 5000); assert.notEqual(advance.receipt_number, data.receipt_number);
  const changed = JSON.parse(storage.get(key));
  changed.subjects.find(s => s.id === changed.groups[0].subject_id).name = 'Changed';
  changed.students.find(s => s.id === student.id).level_id = 1;
  storage.set(key, JSON.stringify(changed));
  const frozen = await devInvoke('cmd_get_receipt_data', { receiptId });
  assert.deepEqual(frozen.items, data.items); assert.equal(frozen.student_level, data.student_level);
  console.log('Receipt backend: centre, 1/3 invoices, partial, advance, distinct batches and snapshots passed');
} finally { await server.close(); }

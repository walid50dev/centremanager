// Run against an isolated preview: VITE_LOAD_TEST_FIXTURE=1 npm run dev -- --host 0.0.0.0 --port 4175
import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const options={headless:true};
if(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH) options.executablePath=process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH;
if(process.env.PLAYWRIGHT_NO_SANDBOX==='1') options.args=['--no-sandbox'];
const browser=await chromium.launch(options);
const page=await browser.newPage({viewport:{width:1280,height:800},locale:'fr-FR'});
const id=x=>page.getByTestId(x);
const timings={};
try {
  await page.goto(process.env.SCREENSHOT_BASE_URL||'http://localhost:4175');
  await page.locator('input[type=password]').fill('test1234');
  let t=performance.now(); await page.locator('form button[type=submit]').click();
  await id('kpi-students').getByText('200',{exact:true}).waitFor(); timings.dashboard=performance.now()-t;
  assert.match(await id('kpi-groups').innerText(),/14/);
  t=performance.now(); await id('nav-students').click(); await page.getByText(/1.*20.*200/).waitFor(); timings.students=performance.now()-t;
  const before=await page.locator('tbody tr').first().innerText(); await page.getByRole('button',{name:'Suivant',exact:true}).click();
  await page.waitForFunction(text=>document.querySelector('tbody tr')?.innerText!==text,before);
  await id('students-search').fill('Bennani'); await page.getByText(/Bennani/).first().waitFor();
  assert.ok(await page.locator('tbody tr').count()>0);
  await id('students-search').fill(''); await page.getByText(/1.*20.*200/).waitFor();
  await page.getByLabel('Filtrer par statut').selectOption('inactif'); await page.getByText('Aucun élève trouvé').waitFor();
  await page.getByLabel('Filtrer par statut').selectOption('actif'); await page.getByText(/1.*20.*200/).waitFor();
  await id('trash-student-200').click(); await page.getByRole('dialog').getByRole('button',{name:'Supprimer',exact:true}).click();
  await page.getByText(/199/).first().waitFor(); await id('nav-trash').click();
  await page.getByRole('button',{name:'Restaurer'}).first().click();
  await id('nav-students').click(); await page.getByText(/1.*20.*200/).waitFor();
  t=performance.now(); await id('nav-groups').click(); await id('group-card-1').waitFor(); timings.groups=performance.now()-t;
  await id('group-card-1').click(); await page.getByRole('dialog').waitFor();
  await page.getByRole('dialog').getByText(/Mathématiques/).first().waitFor(); assert.match(await page.getByRole('dialog').innerText(),/Mathématiques/); await page.getByRole('dialog').getByRole('button',{name:'Fermer',exact:true}).first().click();
  await page.getByRole('dialog').waitFor({state:'hidden'});
  t=performance.now(); await id('nav-payments').click(); await id('section-late').getByText('60 élèves').waitFor(); timings.payments=performance.now()-t;
  assert.match(await id('section-current').innerText(),/140 élèves/);
  await page.getByRole('tab',{name:'Règlements enseignants'}).click();
  const teacherRow=page.getByRole('row').filter({hasText:'Prof. El Amrani'});
  await teacherRow.getByRole('button',{name:'Enregistrer un paiement'}).click();
  await id('settlement-amount').fill('750'); await id('settlement-method').selectOption('virement');
  await id('settlement-notes').fill('Acompte test'); await id('settlement-confirm').click();
  await page.getByRole('dialog').waitFor({state:'hidden'});
  await page.waitForFunction(() => [...document.querySelectorAll('tr')].find(row=>row.textContent?.includes('Prof. El Amrani'))?.textContent?.includes('3250.00'));
  t=performance.now(); await id('nav-expenses').click(); await id('expenses-table').waitFor(); timings.expenses=performance.now()-t;
  await id('sidebar-school-year').selectOption('2'); await page.getByRole('dialog').getByRole('button',{name:'Changer',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('[data-testid="sidebar-school-year"]')?.value==='2');
  await id('nav-students').click(); await page.getByText('Aucun élève trouvé').waitFor();
  await id('sidebar-school-year').selectOption('1'); await page.getByRole('dialog').getByRole('button',{name:'Changer',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('[data-testid="sidebar-school-year"]')?.value==='1');
  await page.getByText(/1.*20.*200/).waitFor();
  console.log('Browser load test passed, observed wall-clock ms:',Object.fromEntries(Object.entries(timings).map(([key,value])=>[key,Math.round(value)])));
} finally {await browser.close();}

import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {createRequire} from 'node:module';
const XLSX=createRequire(import.meta.url)('xlsx');
const browser=await chromium.launch({headless:true,executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1280,height:800},acceptDownloads:true});
const call=(cmd,args={})=>page.evaluate(async({cmd,args})=>(await import('/src/services/settingsDevBackend.ts')).devInvoke(cmd,args),{cmd,args});
try {
 await page.goto(process.env.SCREENSHOT_BASE_URL||'http://localhost:1420');
 await page.locator('input[type=password]').waitFor();
 await page.evaluate(async()=>{const {authApi}=await import('/src/services/auth.ts'); await authApi.setup('Centre test','admin123');});
 const base=(await call('cmd_get_groups'))[0];
 const gid=await call('cmd_create_group',{data:{name:'Groupe Atlas',subject_id:base.subject_id,level_id:base.level_id,school_year_id:base.school_year_id,monthly_fee_cents:33377,capacity:10,schedules:[]}});
 const sid=await call('cmd_create_student',{data:{first_name:'Salma',last_name:'Essai',phone:'0612345678',guardian_phone:'0712345678',guardian_name:'Parent',level_id:base.level_id,enrollment_date:'2026-09-01',status:'actif'}});
 await page.reload(); await page.locator('input[type=password]').fill('admin123'); await page.locator('form button[type=submit]').click();
 await page.getByTestId('nav-students').click();
 await page.getByTestId('view-student-'+sid).click();
 await page.getByRole('tab',{name:'Groupes et tarifs'}).click();
 await page.getByRole('button',{name:'Inscrire à un groupe'}).first().click();
 const dialog=page.getByTestId('enrollment-modal');
 const groupLabel=dialog.locator('label').filter({hasText:'333.77'}).last();
 await groupLabel.locator('input[type=checkbox]').check();
 await dialog.getByRole('button',{name:'Suivant'}).click();
 const fee=page.getByTestId(`enrollment-fee-${gid}`); await fee.waitFor();
 assert.match(await fee.inputValue(),/333/); await fee.fill('175');
 await dialog.getByRole('button',{name:'Suivant'}).click();
 assert.match(await dialog.innerText(),/175/);
 await dialog.getByRole('button',{name:'Suivant'}).click();
 await dialog.getByRole('button',{name:"Confirmer l'inscription"}).click(); await dialog.waitFor({state:'hidden'});
 const invoices=await call('cmd_get_student_invoices',{studentId:sid}); assert.equal(invoices[0].amount_cents,17500);
 await page.getByRole('tab',{name:'Historique des paiements'}).click();
 await page.getByTestId('student-invoices').waitFor(); assert.equal(await page.getByTestId(`whatsapp-${invoices[0].id}`).count(),0); assert.equal(await page.getByTestId('student-sheet').locator('a[href*="wa.me"]').count(),2);
 await page.getByTestId('student-sheet').getByRole('button',{name:'Fermer'}).first().click();
 await page.getByTestId('nav-settings').click();
 await page.getByRole('button',{name:/Année scolaire/}).first().click();
 const year=await call('cmd_get_active_school_year');
 let download=page.waitForEvent('download'); await page.getByTestId(`year-excel-${year.id}`).click(); let file=await download; const workbook=XLSX.readFile(await file.path());
 assert.deepEqual(workbook.SheetNames,['Élèves','Paiements','Dépenses','Professeurs','Groupes','Paiements professeurs']);
 assert.ok(XLSX.utils.sheet_to_json(workbook.Sheets['Élèves']).some(r=>r.first_name==='Salma'&&r.last_name==='Essai'));
 await page.getByText('Fichier exporté avec succès').first().waitFor();
 await page.evaluate(async () => (await import('/src/components/ui/Toast.tsx')).useToastStore.getState().clear());
 download=page.waitForEvent('download'); await page.getByTestId(`year-pdf-${year.id}`).click(); file=await download; assert.match(file.suggestedFilename(),/\.pdf$/); await page.getByText('Fichier exporté avec succès').first().waitFor();
 console.log('Browser: custom fee, WhatsApp URL and multi-sheet Excel/PDF export passed.');
} finally {await browser.close();}

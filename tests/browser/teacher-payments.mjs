// Start Vite first; run node tests/browser/teacher-payments.mjs.
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
const opts = {headless:true};
if (process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH) opts.executablePath=process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH;
if (process.env.PLAYWRIGHT_NO_SANDBOX === '1') opts.args=['--no-sandbox'];
const browser=await chromium.launch(opts);
const context=await browser.newContext({viewport:{width:1280,height:800},locale:'fr-FR'});
const page=await context.newPage();
const id = name => page.getByTestId(name);
const call = (cmd,args={}) => page.evaluate(async ({cmd,args}) => (await import('/src/services/settingsDevBackend.ts')).devInvoke(cmd,args), {cmd,args});
try {
  await page.goto(process.env.SCREENSHOT_BASE_URL || 'http://localhost:1420');
  await page.locator('input[type=password]').first().waitFor();
  await page.evaluate(async () => { const {authApi} = await import('/src/services/auth.ts'); await authApi.setup('Centre test','admin123'); });
  const teacherId = await call('cmd_create_teacher', {data:{full_name:'Prof Sans Config',phone:null,email:null,notes:null,subject_ids:[]}});
  const secondYear = await call('cmd_create_school_year', {label:'2030-2031',startDate:'2030-09-01',endDate:'2031-06-30'});
  await page.evaluate(({teacherId,secondYear}) => {
    const key='centremanager.dev.settings_store_v1'; const store=JSON.parse(localStorage.getItem(key));
    store.teacherYears[teacherId].push(secondYear);
    store.teacherSettlements.push({id:990,teacher_id:teacherId,amount_cents:6000,payment_method:'chèque',notes:'Ancien sans période',month:null,year:null,created_at:'2023-01-01 00:00:00'});
    localStorage.setItem(key,JSON.stringify(store));
  }, {teacherId,secondYear});
  await page.reload(); await page.locator('input[type=password]').fill('admin123'); await page.locator('form button[type=submit]').click();
  await id('nav-teachers').click(); await id(`teacher-card-${teacherId}`).click();
  await page.getByRole('heading', {name:'Prof Sans Config'}).waitFor();
  assert.equal(await page.getByRole('tab',{name:'Activités'}).count(),0);
  assert.match(await id('compensation-config').innerText(), /Estimation indicative.*paiement réel.*manuellement/i);
  assert.ok(await id('comp-mode').locator('option[value=fixed_monthly]').count());
  assert.ok(await id('comp-mode').locator('option[value=percentage]').count());
  await page.getByRole('tab',{name:'Paiements',exact:true}).click();
  await id('teacher-unattributed').waitFor(); await id('teacher-unattributed').locator('summary').click();
  assert.match(await id('teacher-unattributed').innerText(), /Ancien sans période/);
  assert.doesNotMatch(await id('teacher-paid-total').innerText(), /60[,.]00/);
  await id('comp-settle').click();
  const dialog=page.getByRole('dialog').last();
  await id('settlement-amount').waitFor();
  assert.equal(await dialog.locator('input:not([type=hidden]),select,textarea').count(),4);
  assert.equal(await dialog.locator('label .text-red-500').count(),3);
  await id('settlement-date').fill(''); await id('settlement-confirm').click();
  for (const name of ['settlement-amount','settlement-date','settlement-method']) assert.equal(await id(name).getAttribute('aria-invalid'),'true');
  assert.match(await dialog.innerText(), /obligatoire/i);
  const amount=id('settlement-amount'); await amount.click();
  assert.deepEqual(await amount.evaluate(e=>[e.selectionStart,e.selectionEnd,e.value.length]),[0,1,1]);
  await page.keyboard.type('450.25'); assert.equal(await amount.inputValue(),'450.25');
  await id('settlement-date').fill('2024-11-10'); await id('settlement-method').selectOption('virement'); await id('settlement-notes').fill('Acompte manuel');
  await id('settlement-confirm').click(); await dialog.waitFor({state:'hidden'});
  await page.getByText('Acompte manuel').waitFor();
  assert.match(await id('teacher-settlements').innerText(),/10\/11\/2024/);
  assert.match(await id('teacher-settlements').innerText(),/450[,.]25/);
  assert.match(await id('teacher-settlements').innerText(),/Virement/);
  assert.match(await id('teacher-paid-total').innerText(),/450[,.]25/);
  // Use the actual year switcher, including its confirmation dialog.
  await id('sidebar-school-year').selectOption(String(secondYear));
  await page.getByRole('dialog').getByRole('button',{name:'Changer',exact:true}).click();
  await page.waitForFunction(year => document.querySelector('[data-testid="sidebar-school-year"]')?.value === String(year),secondYear);
  await page.getByRole('tab',{name:'Paiements',exact:true}).click();
  await id('teacher-paid-total').waitFor();
  assert.equal(await page.getByText('Acompte manuel').count(),0);
  assert.match(await id('teacher-paid-total').innerText(), /0[,.]00/);
  await id('sidebar-school-year').selectOption('1');
  await page.getByRole('dialog').getByRole('button',{name:'Changer',exact:true}).click();
  await page.waitForFunction(() => document.querySelector('[data-testid="sidebar-school-year"]')?.value === '1');
  await page.getByRole('tab',{name:'Paiements',exact:true}).click();
  await page.getByText('Acompte manuel').waitFor();
  // Independent entry point on the payments page, no configuration required.
  await id('nav-payments').click(); await page.getByRole('tab',{name:/Règlements enseignants/}).click();
  await page.getByRole('button',{name:'العربية',exact:true}).click();
  const row=page.getByRole('row').filter({hasText:'Prof Sans Config'}); await row.getByRole('button',{name:'تسجيل دفعة'}).click();
  await id('settlement-date').fill(''); await id('settlement-confirm').click();
  assert.match(await page.getByRole('dialog').last().innerText(), /مطلوب/);
  console.log('Browser: no activities, estimate, four-field payment, validation, history, year isolation, payments page and Arabic passed.');
} finally { await browser.close(); }

// Start Vite separately, then: node tests/browser/group-form.mjs
// Use PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH for a locally installed Chromium.
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
const launch = { headless:true };
if (process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH) launch.executablePath = process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH;
if (process.env.PLAYWRIGHT_NO_SANDBOX === '1') launch.args = ['--no-sandbox'];
const browser = await chromium.launch(launch);
const context = await browser.newContext({ viewport:{ width:1280, height:800 }, locale:'fr-FR' });
const page = await context.newPage();
const testId = id => page.getByTestId(id);
const call = (cmd, args = {}) => page.evaluate(async ({cmd,args}) => (await import('/src/services/settingsDevBackend.ts')).devInvoke(cmd,args), {cmd,args});
try {
  await page.goto(process.env.SCREENSHOT_BASE_URL || 'http://localhost:1420');
  await page.locator('input[type=password]').first().waitFor();
  await page.evaluate(async () => { const { authApi } = await import('/src/services/auth.ts'); await authApi.setup('Centre test', 'admin123'); });
  await page.reload();
  await page.locator('input[type=password]').fill('admin123');
  await page.locator('form button[type=submit]').click();
  await testId('nav-groups').click();
  await page.getByRole('button', { name:'Nouveau groupe' }).first().click();
  const dialog = page.getByRole('dialog').last();
  await dialog.getByRole('button', { name:'Enregistrer' }).click();
  await testId('group-subject-error').waitFor();
  await testId('group-level-error').waitFor();
  assert.match(await dialog.textContent(), /tarif.*supérieur/i);
  await testId('group-name').fill('Groupe rapide');
  await testId('group-subject-trigger').click(); await testId('group-subject-option-1').click();
  await testId('group-level-trigger').click(); await testId('group-level-option-12').click();
  assert.equal(await dialog.locator('[data-testid$="-toggle"]:checked').count(), 0);
  const fee = testId('group-fee');
  await fee.click();
  assert.deepEqual(await fee.evaluate(e => [e.selectionStart, e.selectionEnd, e.value.length]), [0,1,1]);
  await page.keyboard.type('450.25');
  assert.equal(await fee.inputValue(), '450.25');
  assert.equal(await fee.evaluate(e => getComputedStyle(e).transform), 'none');
  // Inserting at a deliberate caret position must not jump to the end.
  await fee.evaluate(e => e.setSelectionRange(1,1)); await page.keyboard.type('9');
  assert.equal(await fee.inputValue(), '4950.25');
  assert.equal(await fee.evaluate(e => e.selectionStart), 2);
  // Invalid characters and extra fractional digits must not move the caret.
  await page.keyboard.type('x');
  assert.equal(await fee.inputValue(), '4950.25');
  assert.equal(await fee.evaluate(e => e.selectionStart), 2);
  await fee.evaluate(e => e.setSelectionRange(1,1));
  await page.keyboard.type('0');
  assert.equal(await fee.inputValue(), '40950.25');
  assert.equal(await fee.evaluate(e => e.selectionStart), 2);
  await fee.evaluate(e => e.setSelectionRange(0,e.value.length));
  await page.keyboard.type('4950.25');
  await dialog.getByRole('button', { name:'Enregistrer' }).click();
  await dialog.waitFor({ state:'hidden' });
  const row = (await call('cmd_get_groups')).find(g => g.monthly_fee_cents === 495025 && !g.schedules.length);
  assert.ok(row, 'created group has no schedules');
  assert.equal(row.room, null);
  assert.ok(!(await call('cmd_get_timetable')).some(g => g.group_id === row.id));
  await testId('nav-timetable').click();
  await testId('timetable-manage').click();
  await testId('timetable-group').selectOption(String(row.id));
  await testId('timetable-add-slot').click();
  const slot = testId('timetable-slot').first();
  await slot.locator('input[type=time]').first().fill('04:00');
  await slot.locator('input[type=time]').last().fill('05:00');
  await testId('timetable-save').click(); await page.waitForTimeout(400);
  assert.ok((await call('cmd_get_timetable')).some(g => g.group_id === row.id && g.start_time === '04:00'));
  await testId('timetable-manage').click(); await testId('timetable-group').selectOption(String(row.id));
  await testId('timetable-slot').first().getByRole('button',{name:'Supprimer'}).click();
  await testId('timetable-save').click(); await page.waitForTimeout(400);
  assert.ok(!(await call('cmd_get_timetable')).some(g => g.group_id === row.id));
  await testId('nav-students').click();
  await page.getByRole('button', { name:/nouvel élève/i }).first().click();
  await testId('student-save').click();
  for (const id of ['student-first-name','student-last-name','student-guardian-name','student-guardian-phone']) assert.equal(await testId(id).getAttribute('aria-invalid'), 'true');
  assert.equal(await testId('student-level-trigger').getAttribute('aria-required'), 'true');
  assert.equal(await testId('student-level-trigger').getAttribute('aria-invalid'), 'true');
  await page.evaluate(async () => (await import('/src/i18n/index.ts')).default.changeLanguage('ar'));
  assert.match(await testId('student-level-error').textContent(), /مطلوب/);
  await page.evaluate(async () => (await import('/src/i18n/index.ts')).default.changeLanguage('fr'));
  await page.getByRole('dialog').last().getByRole('button', { name:'Fermer', exact:true }).first().click(); await page.waitForTimeout(250);
  await testId('nav-teachers').click(); await testId('teacher-new').click();
  await page.getByRole('dialog').last().getByRole('button', { name:'Enregistrer' }).click();
  assert.equal(await page.getByRole('dialog').last().getByLabel(/nom complet/i).getAttribute('aria-invalid'), 'true');
  console.log('Browser: required errors, select-on-focus, typing/caret, time width, optional group creation/edit/timetable passed.');
} finally { await browser.close(); }

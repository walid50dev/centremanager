import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
import { createServer } from 'vite';
const dom = new JSDOM('<!doctype html><div id="root"></div>', { url: 'http://localhost/' });
Object.assign(globalThis, { window: dom.window, document: dom.window.document, localStorage: dom.window.localStorage, Element: dom.window.Element, HTMLElement: dom.window.HTMLElement, Event: dom.window.Event, IS_REACT_ACT_ENVIRONMENT: true });
const React = await import('react'); const { act } = React; const { createRoot } = await import('react-dom/client');
const server = await createServer({ server: { middlewareMode: true, hmr: false }, appType: 'custom' });
const wait = ms => new Promise(resolve => setTimeout(resolve,ms));
const click = async el => { assert.ok(el); await act(async () => { el.click(); await wait(180); }); };
try {
  await server.ssrLoadModule('/src/i18n/index.ts');
  const { useAppStore } = await server.ssrLoadModule('/src/stores/appStore.ts');
  const { devInvoke } = await server.ssrLoadModule('/src/services/settingsDevBackend.ts');
  const { default: SchoolYearSection } = await server.ssrLoadModule('/src/components/settings/SchoolYearSection.tsx');
  const { default: TrashButton } = await server.ssrLoadModule('/src/components/ui/TrashButton.tsx');
  const { default: TrashPage } = await server.ssrLoadModule('/src/pages/TrashPage.tsx');
  const initial = await devInvoke('cmd_get_active_school_year');
  const other = await devInvoke('cmd_create_school_year', { label:'2030-2031', startDate:'2030-09-01', endDate:'2031-06-30' });
  const student = (await devInvoke('cmd_get_students', {})).data[0];
  await useAppStore.getState().loadSchoolYears();
  const root = createRoot(document.getElementById('root'));
  await act(async () => { root.render(React.createElement(React.Fragment,null,React.createElement(SchoolYearSection), React.createElement(TrashButton,{type:'student',id:student.id,name:student.full_name,onDeleted:()=>{}}))); await wait(400); });
  await click(document.querySelector('section button[aria-expanded]'));
  const activeButton = document.querySelector(`[data-testid="year-delete-${initial.id}"]`);
  assert.ok(activeButton.disabled); assert.match(activeButton.parentElement.title,/active/i);
  await click(document.querySelector(`[data-testid="year-delete-${other}"]`));
  let dialog = document.querySelector('[role="dialog"]'); assert.ok(dialog); assert.match(dialog.textContent,/2030-2031/);
  assert.ok((await devInvoke('cmd_get_school_years')).some(y => y.id === other));
  await click([...dialog.querySelectorAll('button')].find(b => b.textContent.includes('Supprimer')));
  assert.ok(!(await devInvoke('cmd_get_school_years')).some(y => y.id === other));
  await click(document.querySelector(`[data-testid="trash-student-${student.id}"]`));
  dialog = document.querySelector('[role="dialog"]'); assert.ok(dialog); assert.match(dialog.textContent,new RegExp(student.full_name)); assert.match(dialog.textContent,/toutes les années/i);
  assert.ok((await devInvoke('cmd_get_students', {})).data.some(s => s.id === student.id));
  await click([...dialog.querySelectorAll('button')].find(b => b.textContent.trim() === 'Supprimer'));
  await act(async () => { await wait(200); });
  assert.ok(!(await devInvoke('cmd_get_students', {})).data.some(s => s.id === student.id));
  const expense = (await devInvoke('cmd_get_expenses', { month: new Date().getMonth()+1, year: new Date().getFullYear() }))[0];
  assert.ok(expense, "expected an expense fixture");
  {
    await devInvoke('cmd_delete_to_trash', { entityType:'expense', entityId:expense.id });
    await act(async () => { root.render(React.createElement(TrashPage)); });
    await act(async () => { await wait(300); });
    const emptyButton = [...document.querySelectorAll('button')].find(b => b.textContent.includes('Vider la corbeille'));
    await click(emptyButton);
    dialog = document.querySelector('[role="dialog"]'); assert.ok(dialog); assert.match(dialog.textContent,/irréversible/i);
    assert.ok((await devInvoke('cmd_list_trash')).some(x => x.entity_id === expense.id && x.entity_type === 'expense'));
    await click([...dialog.querySelectorAll('button')].find(b => b.textContent.includes('Vider')));
    assert.ok(!(await devInvoke('cmd_list_trash')).some(x => x.entity_id === expense.id && x.entity_type === 'expense'));
  }
  await act(async () => root.unmount());
  console.log('UI: active year disabled; year, student and empty-trash confirmations passed');
} finally { await server.close(); dom.window.close(); }
